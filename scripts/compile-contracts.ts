/**
 * Compiles contracts/*.sol with solc and writes typed ABI + bytecode modules:
 *   src/contracts/escrow.ts      (used by the server and the deploy script)
 *   scripts/build/testToken.ts   (tests only)
 * Run: npm run compile:contracts
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");

const files = ["contracts/ProofPayEscrow.sol", "contracts/test/TestToken.sol"];
const input = {
  language: "Solidity",
  sources: Object.fromEntries(files.map((f) => [f, { content: fs.readFileSync(path.join(root, f), "utf8") }])),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

function findImports(importPath: string) {
  try {
    return { contents: fs.readFileSync(require.resolve(importPath), "utf8") };
  } catch {
    return { error: `Not found: ${importPath}` };
  }
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors || []).filter((e: { severity: string }) => e.severity === "error");
for (const e of output.errors || []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

function emit(file: string, contract: string, name: string, outFile: string) {
  const c = output.contracts[file][contract];
  const body =
    `// Generated by scripts/compile-contracts.ts from ${file}. Do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(c.abi, null, 2)} as const;\n\n` +
    `export const ${name}Bytecode = "0x${c.evm.bytecode.object}" as const;\n`;
  fs.mkdirSync(path.dirname(path.join(root, outFile)), { recursive: true });
  fs.writeFileSync(path.join(root, outFile), body);
  console.log(`wrote ${outFile} (${c.evm.bytecode.object.length / 2} bytes)`);
}

emit("contracts/ProofPayEscrow.sol", "ProofPayEscrow", "escrow", "src/contracts/escrow.ts");
emit("contracts/test/TestToken.sol", "TestToken", "testToken", "scripts/build/testToken.ts");
